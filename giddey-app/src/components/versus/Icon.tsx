export type IconName = keyof typeof ICONS;

/** Lucide icon by name. Inline-sized to the text by default (1.1em). */
export default function Icon({ name, size = '1.1em', className = '', strokeWidth = 2.25, ...rest }: { name: IconName | string; size?: number | string } & Omit<LucideProps, 'size' | 'name'>) {
	const C = (ICONS as Record<string, LucideIcon>)[name];
	// legacy data (old saves, shared careers) may still carry an emoji — show it as text
	if (!C) return /^[a-zA-Z]+$/.test(name) ? <ICONS.ball size={size} strokeWidth={strokeWidth} className={`inline-block shrink-0 align-[-0.15em] ${className}`} aria-hidden /> : <span className={className} aria-hidden>{name}</span>;
	return <C size={size} strokeWidth={strokeWidth} className={`inline-block shrink-0 align-[-0.15em] ${className}`} aria-hidden {...rest} />;
}

/** Icon in a soft tinted square — for list rows and cards */
export function IconTile({ name, color = '#f97316', size = 36, className = '' }: { name: IconName | string; color?: string; size?: number; className?: string }) {
	return (
		<span className={`inline-flex items-center justify-center rounded-xl shrink-0 ${className}`} style={{ width: size, height: size, background: `${color}22`, color, boxShadow: `inset 0 0 0 1px ${color}44` }}>
			<Icon name={name} size={Math.round(size * 0.55)} />
		</span>
	);
}
